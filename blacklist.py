def mask_word(word):
    if len(word) <= 2:
        return word[0] + "*" * (len(word) - 1)
    return word[0] + "*" * (len(word) - 2) + word[-1]


def blocked(word):
    folded = word.replace("ё", "е").replace("Ё", "Е")
    if ALLOW.fullmatch(folded):
        return False
    return bool(BLACKLIST.fullmatch(folded) or SENSITIVE_RE.fullmatch(folded) or OBSCENE.fullmatch(folded))


def mask_digits(match):
    text = match.group()
    digits = [i for i, ch in enumerate(text) if ch.isdigit()]
    if len(digits) < 7:
        return text
    keep = {digits[0], digits[-1]}
    return "".join("*" if ch.isdigit() and i not in keep else ch for i, ch in enumerate(text))


def mask(text):
    text = WORD.sub(lambda m: mask_word(m.group()) if blocked(m.group()) else m.group(), text)
    return DIGITS.sub(mask_digits, text)
